import { Router } from 'express';
import type { AppEnv } from '../config/env.js';
import type { SystemController } from '../controllers/system.controller.js';
import type { AuthController } from '../controllers/auth.controller.js';
import type { AuthRepository } from '../repositories/auth.repository.js';
import { createSystemRouter } from './system.routes.js';
import { createAuthRouter } from './auth.routes.js';
import type { CatalogController } from '../controllers/catalog.controller.js';
import { createCatalogRouter } from './catalog.routes.js';
import type { MediaController } from '../controllers/media.controller.js';
import { createMediaRouter } from './media.routes.js';
import type { AccountController } from '../controllers/account.controller.js';
import { createAccountRouter } from './account.routes.js';
import type { CartController } from '../controllers/cart.controller.js';
import { createCartRouter } from './cart.routes.js';
import type { BookingController } from '../controllers/booking.controller.js';
import { createBookingRouter } from './booking.routes.js';
import type { TechnicianController } from '../controllers/technician.controller.js';
import { createTechnicianRouter } from './technician.routes.js';
import type { PricingController } from '../controllers/pricing.controller.js';
import { createPricingRouter } from './pricing.routes.js';
import type { CheckoutController } from '../controllers/checkout.controller.js';
import { createCheckoutRouter } from './checkout.routes.js';
import type { PaymentController } from '../controllers/payment.controller.js';
import { createPaymentRouter } from './payment.routes.js';
import type { OrderController } from '../controllers/order.controller.js';
import { createOrderRouter } from './order.routes.js';
import type { RefundController } from '../controllers/refund.controller.js';
import { createRefundRouter } from './refund.routes.js';
import type { ReturnController } from '../controllers/return.controller.js';
import { createReturnRouter } from './return.routes.js';
import type { ShippingController } from '../controllers/shipping.controller.js';
import { createShippingRouter } from './shipping.routes.js';
import type { NotificationController } from '../controllers/notification.controller.js';
import { createNotificationRouter } from './notification.routes.js';
import type { AdminOperationsController } from '../controllers/admin-operations.controller.js';
import { createAdminOperationsRouter } from './admin-operations.routes.js';
import type { AdminCatalogController } from '../controllers/admin-catalog.controller.js';
import { createAdminCatalogRouter } from './admin-catalog.routes.js';
import type { SubscriptionController } from '../controllers/subscription.controller.js';
import { createSubscriptionRouter } from './subscription.routes.js';
import type { OpsController } from '../controllers/ops.controller.js';
import { createOpsRouter } from './ops.routes.js';

export function createApiRouter(dependencies: { env: AppEnv; systemController: SystemController; authController: AuthController; authRepository: AuthRepository; catalogController: CatalogController; mediaController: MediaController; accountController: AccountController; cartController: CartController; bookingController: BookingController; technicianController: TechnicianController; pricingController: PricingController; checkoutController: CheckoutController; paymentController: PaymentController; orderController: OrderController; refundController: RefundController; returnController: ReturnController; shippingController: ShippingController; notificationController: NotificationController; adminOperationsController: AdminOperationsController; adminCatalogController: AdminCatalogController; subscriptionController: SubscriptionController; opsController: OpsController }) {
  const router = Router();
  router.use(createSystemRouter(dependencies.systemController));
  router.use(createAuthRouter(dependencies.env, dependencies.authController, dependencies.authRepository));
  router.use(createCatalogRouter(dependencies.catalogController));
  router.use(createMediaRouter(dependencies.env, dependencies.mediaController, dependencies.authRepository));
  router.use(createAccountRouter(dependencies.env, dependencies.accountController, dependencies.authRepository));
  router.use(createCartRouter(dependencies.env, dependencies.cartController, dependencies.authRepository));
  router.use(createBookingRouter(dependencies.env, dependencies.bookingController, dependencies.authRepository));
  router.use(createTechnicianRouter(dependencies.env, dependencies.technicianController, dependencies.authRepository));
  router.use(createPricingRouter(dependencies.env, dependencies.pricingController, dependencies.authRepository));
  router.use(createCheckoutRouter(dependencies.env, dependencies.checkoutController, dependencies.authRepository));
  router.use(createPaymentRouter(dependencies.env, dependencies.paymentController, dependencies.authRepository));
  router.use(createOrderRouter(dependencies.env, dependencies.orderController, dependencies.authRepository));
  router.use(createRefundRouter(dependencies.env, dependencies.refundController, dependencies.authRepository));
  router.use(createReturnRouter(dependencies.env, dependencies.returnController, dependencies.authRepository));
  router.use(createShippingRouter(dependencies.env, dependencies.shippingController, dependencies.authRepository));
  router.use(createNotificationRouter(dependencies.env, dependencies.notificationController, dependencies.authRepository));
  router.use(createAdminOperationsRouter(dependencies.env, dependencies.adminOperationsController, dependencies.authRepository));
  router.use(createAdminCatalogRouter(dependencies.env, dependencies.adminCatalogController, dependencies.authRepository));
  router.use(createSubscriptionRouter(dependencies.env, dependencies.subscriptionController, dependencies.authRepository));
  router.use(createOpsRouter(dependencies.env, dependencies.opsController, dependencies.authRepository));
  return router;
}
