#!/usr/bin/env python3
"""Create/check the Phase 0 Supabase dependency freeze.

Usage:
  python tool/phase0_backend_freeze_audit.py --write
  python tool/phase0_backend_freeze_audit.py --check

The freeze is intentionally a snapshot. During later phases use it as the
migration checklist; do not silently regenerate it after removing a dependency.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
SUPABASE = ROOT / "supabase"
MANIFEST = ROOT / "docs" / "backend" / "contracts" / "supabase-freeze.json"
MAP = ROOT / "docs" / "backend" / "SUPABASE_DEPENDENCY_MAP.md"

PATTERNS = {
    "tables": re.compile(r"\.from\(\s*['\"]([^'\"]+)['\"]\s*\)"),
    "rpcs": re.compile(r"\.rpc\(\s*['\"]([^'\"]+)['\"]"),
    "functions": re.compile(r"functions\.invoke\(\s*['\"]([^'\"]+)['\"]"),
    "storage_buckets": re.compile(r"storage\.from\(\s*['\"]([^'\"]+)['\"]\s*\)"),
    "auth_methods": re.compile(r"supabase\.auth\.([A-Za-z0-9_]+)"),
}


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def scan():
    consumers = []
    totals = {k: set() for k in PATTERNS}
    for path in sorted(SRC.rglob("*")):
        if not path.is_file() or path.suffix not in {".ts", ".tsx", ".js", ".jsx"}:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        if "supabase" not in text and "@supabase" not in text:
            continue
        usage = {}
        for name, pattern in PATTERNS.items():
            values = sorted(set(pattern.findall(text)))
            if values:
                usage[name] = values
                totals[name].update(values)
        consumers.append({"file": rel(path), **usage})

    edge_dirs = []
    functions_dir = SUPABASE / "functions"
    if functions_dir.exists():
        edge_dirs = sorted(p.name for p in functions_dir.iterdir() if p.is_dir())

    migration_files = []
    migrations_dir = SUPABASE / "migrations"
    if migrations_dir.exists():
        migration_files = sorted(rel(p) for p in migrations_dir.rglob("*") if p.is_file())

    tracked_files = [ROOT / c["file"] for c in consumers]
    for folder in (functions_dir, migrations_dir):
        if folder.exists():
            tracked_files.extend(p for p in folder.rglob("*") if p.is_file())

    digest = hashlib.sha256()
    for path in sorted(tracked_files, key=lambda p: rel(p)):
        digest.update(rel(path).encode())
        digest.update(sha256(path).encode())

    return {
        "phase": 0,
        "contract_version": "v1",
        "purpose": "Immutable source snapshot for Supabase-to-Express/PostgreSQL migration tracking",
        "counts": {
            "frontend_supabase_consumers": len(consumers),
            "distinct_frontend_rpcs": len(totals["rpcs"]),
            "supabase_function_directories_including_shared": len(edge_dirs),
            "supabase_business_function_directories": len([x for x in edge_dirs if x != "_shared"]),
            "supabase_migration_files": len(migration_files),
        },
        "distinct": {k: sorted(v) for k, v in totals.items()},
        "edge_function_directories": edge_dirs,
        "migration_files": migration_files,
        "frontend_consumers": consumers,
        "snapshot_sha256": digest.hexdigest(),
    }


def markdown(data):
    lines = [
        "# Supabase Dependency Map — Phase 0 Freeze",
        "",
        "This is generated by `python tool/phase0_backend_freeze_audit.py --write`.",
        "It is a migration checklist, not a recommendation to keep these dependencies.",
        "",
        "## Counts",
        "",
    ]
    for k, v in data["counts"].items():
        lines.append(f"- `{k}`: **{v}**")
    lines += ["", "## Distinct RPCs", ""]
    lines += [f"- `{x}`" for x in data["distinct"]["rpcs"]]
    lines += ["", "## Frontend-invoked Edge Functions", ""]
    lines += [f"- `{x}`" for x in data["distinct"]["functions"]]
    lines += ["", "## Supabase function directories", ""]
    lines += [f"- `{x}`" for x in data["edge_function_directories"]]
    lines += ["", "## Directly referenced tables/buckets", ""]
    lines += [f"- table `{x}`" for x in data["distinct"]["tables"]]
    lines += [f"- storage bucket `{x}`" for x in data["distinct"]["storage_buckets"]]
    lines += ["", "## Frontend consumers", ""]
    lines.append("| File | Tables | RPCs | Edge functions | Auth | Storage |")
    lines.append("|---|---|---|---|---|---|")
    for c in data["frontend_consumers"]:
        fmt = lambda key: ", ".join(f"`{x}`" for x in c.get(key, [])) or "—"
        lines.append(
            f"| `{c['file']}` | {fmt('tables')} | {fmt('rpcs')} | {fmt('functions')} | {fmt('auth_methods')} | {fmt('storage_buckets')} |"
        )
    lines += [
        "",
        "## Migration rule",
        "",
        "A consumer is considered migrated only when it no longer imports/calls Supabase at runtime and its replacement `/api/v1` path has regression coverage. Do not delete the original R1–R8 authority implementation until its replacement passes the corresponding invariant tests.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()

    data = scan()
    if args.write:
        MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        MANIFEST.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        MAP.write_text(markdown(data), encoding="utf-8")
        print("PHASE 0 BACKEND FREEZE: WRITTEN")
        print(json.dumps(data["counts"], indent=2))
        return 0

    if not MANIFEST.exists():
        print("FAIL: freeze manifest is missing", file=sys.stderr)
        return 2
    expected = json.loads(MANIFEST.read_text(encoding="utf-8"))
    problems = []
    baseline_counts = expected.get("counts", {})
    # The Phase 0 manifest is immutable, but later phases are expected to REMOVE
    # runtime Supabase consumers. `--check` therefore rejects dependency growth,
    # new RPC/table/function/bucket/auth usage, or mutation of the frozen Supabase
    # backend artifacts while allowing planned frontend migrations to reduce usage.
    for key in ("frontend_supabase_consumers", "distinct_frontend_rpcs"):
        if data["counts"].get(key, 0) > baseline_counts.get(key, 0):
            problems.append(f"{key} increased above Phase 0 baseline: {data['counts'].get(key)} > {baseline_counts.get(key)}")
    for key in ("supabase_function_directories_including_shared", "supabase_business_function_directories", "supabase_migration_files"):
        if data["counts"].get(key) != baseline_counts.get(key):
            problems.append(f"frozen Supabase artifact count changed for {key}: expected {baseline_counts.get(key)} got {data['counts'].get(key)}")
    for key in ("tables", "rpcs", "functions", "storage_buckets", "auth_methods"):
        current=set(data.get("distinct", {}).get(key, [])); baseline=set(expected.get("distinct", {}).get(key, []))
        extra=sorted(current-baseline)
        if extra:
            problems.append(f"new Supabase {key} dependencies introduced after Phase 0: {extra}")
    if data.get("edge_function_directories") != expected.get("edge_function_directories"):
        problems.append("frozen Supabase Edge Function directories changed")
    if data.get("migration_files") != expected.get("migration_files"):
        problems.append("frozen Supabase migration artifact list changed")
    if problems:
        print("PHASE 0 BACKEND FREEZE: FAIL")
        for p in problems:
            print(f"- {p}")
        return 1
    print("PHASE 0 BACKEND FREEZE: PASS")
    print(json.dumps({"baseline": baseline_counts, "current": data["counts"]}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
