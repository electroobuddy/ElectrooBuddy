from pathlib import Path
import sys
root=Path(__file__).resolve().parents[1]
checks=[]
def check(name, cond): checks.append((name,bool(cond)))
def read(rel): return (root/rel).read_text(encoding='utf-8')
orders=read('src/pages/user/UserOrders.tsx')
native=read('src/lib/nativeOrders.ts')
contracts=read('src/lib/apiContracts.ts')
svc=read('server/src/services/order.service.ts')
ctrl=read('server/src/controllers/order.controller.ts')
routes=read('server/src/routes/order.routes.ts')
tracking=read('src/pages/OrderTracking.tsx')
success=read('src/pages/OrderSuccess.tsx')
check('lifecycle endpoint wrapper', 'getNativeOrderLifecycle' in native and '/orders/${id}/lifecycle' in native)
check('lifecycle route protected', "'/orders/:id/lifecycle'" in routes and "requirePermission('orders:read-own')" in routes)
check('lifecycle controller', 'lifecycle=async' in ctrl)
check('server capabilities', 'can_refund_to_cancel' in svc and 'can_return' in svc and 'return_window_ends_at' in svc)
check('server lifecycle includes refunds', 'order_refunds' in svc and 'refundable_amount' in svc)
check('server lifecycle includes returns', 'order_returns' in svc and 'has_active_return' in svc)
check('return remaining quantity', 'return_eligible_quantity' in svc and 'prior_quantity' in svc)
check('typed lifecycle contract', 'interface NativeOrderLifecycle' in contracts and 'OrderPostPurchaseCapabilities' in contracts)
check('typed tracking', 'useState<NativeOrderTracking|null>' in tracking and 'useState<any>' not in tracking)
check('normalized tracking error', 'nativeApiErrorMessage' in tracking)
check('ui uses server cancel capability', 'order.post_purchase?.can_cancel' in orders)
check('ui uses server refund capability', 'order.post_purchase?.can_refund_to_cancel' in orders)
check('ui uses server return capability', 'order.post_purchase?.can_return' in orders)
check('no local seven-day calculation', '7 * 24 * 60 * 60 * 1000' not in orders and 'Date.now() - new Date(order.delivered_at)' not in orders)
check('stable refund idempotency', 'requestKeyFor(order.id, operation)' in orders and 'refund-cancel' in orders)
check('stable return idempotency', 'requestKeyFor(order.id, `return-${resolution}`)' in orders)
check('refund status displayed', 'lifecycle.refunds.map' in orders and 'provider_status' in orders)
check('return status displayed', 'lifecycle.returns.map' in orders)
check('receipt uses server total', 'order?.total_amount' in success and 'Order Total' in success)
check('receipt exposes refunded amount', 'order?.refunded_amount' in success and 'Refunded' in success)
check('order item total uses persisted total', 'item.total_price' in orders and 'item.quantity * item.price' not in orders)
failed=[n for n,ok in checks if not ok]
for n,ok in checks: print(('PASS' if ok else 'FAIL')+': '+n)
print(f'FAPI-8: {sum(ok for _,ok in checks)}/{len(checks)} PASS')
if failed:
 print('Failed: '+', '.join(failed));sys.exit(1)
